const dicts: Record<Lang, Dict> = { fi, en };
const LANG_KEY = 'stats-prkl:lang';

function initialLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v === 'fi' || v === 'en') return v;
  } catch { /* storage unavailable */ }
  return 'fi';
}

let lang: Lang = typeof window !== 'undefined' ? initialLang() : 'fi';
const listeners = new Set<() => void>();

export function setLang(l: Lang) {
  lang = l;
  try { localStorage.setItem(LANG_KEY, l); } catch { /* ignore */ }
  document.documentElement.lang = l;
  listeners.forEach(f => f());
}

export function useLang(): Lang {
  return useSyncExternalStore(f => { listeners.add(f); return () => listeners.delete(f); }, () => lang);
}

export function useT(): Dict {
  return dicts[useLang()];
}

export const dict = (l: Lang) => dicts[l];
